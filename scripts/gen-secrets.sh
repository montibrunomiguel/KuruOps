#!/usr/bin/env bash
# Generates the credentials docker-compose.secure.yml requires: strong random database
# passwords, an AES-256 encryption key for the secret store, and a JWT keypair.
#
#   bash scripts/gen-secrets.sh            # first time
#   bash scripts/gen-secrets.sh --force    # overwrite what is there (rotates EVERYTHING)
#
# Writes (both are gitignored, never commit them):
#   .env.secure                the passwords and the encryption key, for
#                              `docker compose --env-file .env.secure ...`
#   .secrets/jwt_private.pem   the access-token signing keypair, mounted into the api
#   .secrets/jwt_public.pem
#
# It refuses to overwrite existing files without --force, because the values are not
# interchangeable with what an existing deployment already holds: a new
# SECRETS_ENCRYPTION_KEY cannot decrypt secrets stored under the old one (LLM and MCP API
# keys, SMTP and LDAP passwords ... would all become unreadable), and new database
# passwords only take effect once the roles are re-created (`task db:roles` with the new
# values). Rotate deliberately, not by re-running this.
#
# Needs openssl (Git for Windows ships it).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT/.env.secure"
KEY_DIR="$ROOT/.secrets"
FORCE="${1:-}"

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required (it makes the random values and the JWT keypair)." >&2
  exit 1
fi
if [[ ( -e "$ENV_FILE" || -e "$KEY_DIR/jwt_private.pem" ) && "$FORCE" != "--force" ]]; then
  echo "$ENV_FILE or $KEY_DIR already exists. Re-run with --force to overwrite (this rotates every secret; see the header of this script)." >&2
  exit 1
fi

# base64 of random bytes, with the characters that are awkward in a URL (the passwords go
# into a postgres:// connection string) or a shell removed. 32 bytes of entropy before the
# filtering is far more than enough for a password.
password() { openssl rand -base64 48 | tr -d '/+=\n' | cut -c1-40; }

mkdir -p "$KEY_DIR"
umask 077
{
  echo "# Generated by scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Never commit this file."
  echo "POSTGRES_PASSWORD=$(password)"
  echo "KURUOPS_APP_PASSWORD=$(password)"
  echo "KURUOPS_WORKER_PASSWORD=$(password)"
  # An AES-256 key, base64: exactly what config.Config.SecretsEncryptionKey expects.
  echo "SECRETS_ENCRYPTION_KEY=$(openssl rand -base64 32)"
} >"$ENV_FILE"

openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:3072 -out "$KEY_DIR/jwt_private.pem" 2>/dev/null
openssl rsa -in "$KEY_DIR/jwt_private.pem" -pubout -out "$KEY_DIR/jwt_public.pem" 2>/dev/null
# The api runs as a non-root container user that is not the owner of these files on a
# Linux host, so the mounted keys must be world-readable there. They sit in a gitignored,
# local directory; protect the directory itself (the 700 below) rather than each file.
chmod 644 "$KEY_DIR/jwt_private.pem" "$KEY_DIR/jwt_public.pem"
chmod 700 "$KEY_DIR"

echo "Wrote $ENV_FILE and $KEY_DIR/jwt_{private,public}.pem"
echo "Next:  task deploy:secure:up"
